-- 主表：一人一行（网站行为 + 问卷答案）
create table if not exists experiment_results (
  id bigint generated by default as identity primary key,
  user_id text unique not null,
  ai_style text not null,

  -- 网站行为
  selected_product_id text,
  decision_cost_sec numeric,
  question_count int,
  started_at timestamptz,

  -- 人口学（5 题）
  gender int,
  age_group int,
  education int,
  ai_experience int,
  shop_freq int,

  -- 感知有用性（4 题）
  q_useful_1 int, q_useful_2 int, q_useful_3 int, q_useful_4 int,
  -- 信任（2 题）
  q_trust_1 int, q_trust_2 int,
  -- 采纳意愿（3 题）
  q_intent_1 int, q_intent_2 int, q_intent_3 int,
  -- 满意度（1 题）、易用性（1 题）
  q_satis int, q_easy int,
  -- 持续使用（2 题）
  q_cont_1 int, q_cont_2 int,

  -- 陷阱题（2 题）
  trap_1 int, trap_2 int,
  -- 是否两题都答对（1=通过，0=未通过；分析时可据此剔除）
  trap_passed int,

  -- 元数据
  submitted_at timestamptz default now(),
  duration_sec numeric
);

alter table experiment_results enable row level security;
drop policy if exists "allow_anon_insert" on experiment_results;
create policy "allow_anon_insert" on experiment_results
  for insert to anon with check (true);

-- 兜底表：被试中途关闭页面时，点击行为仍可追溯
create table if not exists behavior_temp (
  id bigint generated by default as identity primary key,
  user_id text,
  ai_style text,
  product_id text,
  decision_cost_sec numeric,
  question_count int,
  created_at timestamptz default now()
);

alter table behavior_temp enable row level security;
drop policy if exists "allow_anon_insert" on behavior_temp;
create policy "allow_anon_insert" on behavior_temp
  for insert to anon with check (true);

